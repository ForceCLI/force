//go:build ignore

// This program writes sf/registry_data.go from the metadata registry of the
// Salesforce source-deploy-retrieve library.  Run it with
//
//	make update-sf-registry SF_REGISTRY_DIR=<checkout of source-deploy-retrieve>
//
// It reads src/registry/metadataRegistry.json and
// src/registry/stdValueSetRegistry.json from the checkout and writes the
// facts the sf-compatible mode uses: the names of the metadata types, the
// folder types, the child types, the types that cannot be named in a
// manifest, the type names that stand for another type, and the names of
// the standard value sets.  It records the version and the commit of the
// checkout in the generated file, and writes the attribution block
// licenses/source-deploy-retrieve.txt, which "make third-party-licenses.txt"
// appends to the license report.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const repository = "https://github.com/forcedotcom/source-deploy-retrieve"

type metadataType struct {
	Name              string `json:"name"`
	FolderContentType string `json:"folderContentType"`
	AliasFor          string `json:"aliasFor"`
	IsAddressable     *bool  `json:"isAddressable"`
	Strategies        struct {
		Recomposition string `json:"recomposition"`
	} `json:"strategies"`
	Children *struct {
		Types map[string]metadataType `json:"types"`
	} `json:"children"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run sf/registry/update.go <source-deploy-retrieve checkout> <force repository root>")
		os.Exit(2)
	}
	checkout, root := os.Args[1], os.Args[2]

	var registry struct {
		Types map[string]metadataType `json:"types"`
	}
	readJSON(filepath.Join(checkout, "src", "registry", "metadataRegistry.json"), &registry)
	var valueSets struct {
		Fullnames []string `json:"fullnames"`
	}
	readJSON(filepath.Join(checkout, "src", "registry", "stdValueSetRegistry.json"), &valueSets)
	var manifest struct {
		Version string `json:"version"`
	}
	readJSON(filepath.Join(checkout, "package.json"), &manifest)
	commit := strings.TrimSpace(output(checkout, "git", "rev-parse", "HEAD"))

	// The types are written in the order of their ids, which is the order
	// sf lists names in.
	ids := make([]string, 0, len(registry.Types))
	for id := range registry.Types {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var names []string
	folders, aliases := map[string]string{}, map[string]string{}
	children := map[string][]string{}
	notAddressable, withoutParent := map[string]bool{}, map[string]bool{}
	for _, id := range ids {
		entry := registry.Types[id]
		names = append(names, entry.Name)
		if entry.FolderContentType != "" {
			folders[entry.Name] = registry.Types[entry.FolderContentType].Name
		}
		if entry.AliasFor != "" {
			aliases[entry.Name] = registry.Types[entry.AliasFor].Name
		}
		if entry.IsAddressable != nil && !*entry.IsAddressable {
			notAddressable[entry.Name] = true
		}
		if entry.Children == nil {
			continue
		}
		childIDs := make([]string, 0, len(entry.Children.Types))
		for childID := range entry.Children.Types {
			childIDs = append(childIDs, childID)
		}
		sort.Strings(childIDs)
		for _, childID := range childIDs {
			child := entry.Children.Types[childID]
			children[entry.Name] = append(children[entry.Name], child.Name)
			if child.IsAddressable != nil && !*child.IsAddressable {
				notAddressable[child.Name] = true
			}
			if entry.Strategies.Recomposition == "startEmpty" {
				withoutParent[child.Name] = true
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by sf/registry/update.go from the metadata registry of the\n")
	fmt.Fprintf(&b, "// Salesforce source-deploy-retrieve library, version %s, commit\n// %s. DO NOT EDIT.\n\npackage sf\n\n", manifest.Version, commit)
	fmt.Fprintf(&b, "// registryTypeNames are the metadata types sf knows, by name, in the order\n// of the registry.\nvar registryTypeNames = []string{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	fmt.Fprintf(&b, "}\n\n// registryFolderContent gives, for a folder type, the type of the components\n// in the folders.\n")
	writeStringMap(&b, "registryFolderContent", folders)
	fmt.Fprintf(&b, "\n// registryTypeAliases are the type names that sf takes for another type.\n")
	writeStringMap(&b, "registryTypeAliases", aliases)
	fmt.Fprintf(&b, "\n// registryChildTypes gives the child types of a type, such as CustomField\n// for CustomObject.\nvar registryChildTypes = map[string][]string{\n")
	for _, parent := range sortedKeys(children) {
		quoted := make([]string, len(children[parent]))
		for i, child := range children[parent] {
			quoted[i] = fmt.Sprintf("%q", child)
		}
		fmt.Fprintf(&b, "\t%q: {%s},\n", parent, strings.Join(quoted, ", "))
	}
	fmt.Fprintf(&b, "}\n\n// registryNotAddressable are the types that cannot be named in a manifest.\n")
	writeSet(&b, "registryNotAddressable", notAddressable)
	fmt.Fprintf(&b, "\n// registryNamedWithoutParent are the child types whose members are listed\n// in a manifest without the name of their parent: CustomLabel.\n")
	writeSet(&b, "registryNamedWithoutParent", withoutParent)
	fmt.Fprintf(&b, "\n// registryStandardValueSets are the standard value sets sf asks an org for.\nvar registryStandardValueSets = []string{\n")
	for _, name := range valueSets.Fullnames {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	fmt.Fprintf(&b, "}\n")
	formatted, err := format.Source(b.Bytes())
	check(err)
	check(os.WriteFile(filepath.Join(root, "sf", "registry_data.go"), formatted, 0o644))
	fmt.Printf("sf/registry_data.go: %d types, %d standard value sets, from %s %s\n", len(names), len(valueSets.Fullnames), manifest.Version, commit)

	// The attribution block has the layout of the blocks go-licenses
	// writes with licenses.tpl.
	license, err := os.ReadFile(filepath.Join(checkout, "LICENSE.txt"))
	check(err)
	rule := strings.Repeat("=", 80)
	notice := rule + "\n" +
		"source-deploy-retrieve " + manifest.Version + " (metadata type names of the sf-compatible mode)\n" +
		"Apache-2.0\n" +
		rule + "\n\n" +
		"Source: " + repository + " commit " + commit + "\n" +
		"sf/registry_data.go holds names taken from the metadata registry of this\n" +
		"library: the metadata types, their folder and child types, and the\n" +
		"standard value sets.  The file is compiled into the binary.\n\n" +
		string(license) + "\n"
	check(os.MkdirAll(filepath.Join(root, "licenses"), 0o755))
	check(os.WriteFile(filepath.Join(root, "licenses", "source-deploy-retrieve.txt"), []byte(notice), 0o644))
}

func writeStringMap(b *bytes.Buffer, name string, values map[string]string) {
	fmt.Fprintf(b, "var %s = map[string]string{\n", name)
	for _, key := range sortedKeys(values) {
		fmt.Fprintf(b, "\t%q: %q,\n", key, values[key])
	}
	fmt.Fprintf(b, "}\n")
}

func writeSet(b *bytes.Buffer, name string, values map[string]bool) {
	fmt.Fprintf(b, "var %s = map[string]bool{\n", name)
	for _, key := range sortedKeys(values) {
		fmt.Fprintf(b, "\t%q: true,\n", key)
	}
	fmt.Fprintf(b, "}\n")
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func readJSON(path string, target interface{}) {
	data, err := os.ReadFile(path)
	check(err)
	check(json.Unmarshal(data, target))
}

func output(dir string, name string, args ...string) string {
	command := exec.Command(name, args...)
	command.Dir = dir
	out, err := command.Output()
	check(err)
	return string(out)
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
